/**
 * Dịch chuỗi cố định do app sinh ra và đã lưu (lý do chấm tự động, phân tích tĩnh, ghi chú quét bài...).
 * Các chuỗi này luôn lưu bằng tiếng Việt; chuỗi không nhận ra (vd output trình biên dịch) giữ nguyên.
 */
export function localizeStored(lang: string, s: string): string {
  if (lang !== 'en' || !s) return s
  const exact = EN[s] ?? EN[s.trim()]
  if (exact) return exact
  const tr = (x: string): string => localizeStored(lang, x)
  for (const [re, fn] of EN_PATTERNS) {
    const m = s.match(re)
    if (m) return fn(m, tr)
  }
  return s
}
