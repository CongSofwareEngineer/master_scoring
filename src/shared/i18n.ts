export function translate(lang: string, s: string, vars?: Record<string, string | number>): string {
  let out = lang === 'en' ? (EN[s] ?? s) : s
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v))
  return out
}

// Thông báo có tham số (do app sinh, lưu bằng tiếng Việt) → English.
const EN_PATTERNS: [RegExp, (m: RegExpMatchArray, tr: (s: string) => string) => string][] = [
  [/^Đạt (\d+)\/(\d+) test case\.$/, (m) => `Passed ${m[1]}/${m[2]} test cases.`],
  [/^Phân tích tĩnh: (\d+) lỗi, (\d+) cảnh báo\.$/, (m) => `Static analysis: ${m[1]} errors, ${m[2]} warnings.`],
  [/^Chưa chấm tự động: (.*) — giáo viên chấm tay\.$/s, (m, tr) => `Not graded automatically: ${tr(m[1])} — graded manually by the teacher.`],
  [/^Hàm "(.+)" dài (\d+) dòng \(> (\d+)\), nên tách nhỏ\.$/, (m) => `Function "${m[1]}" is ${m[2]} lines long (> ${m[3]}); consider splitting it.`],
  [/^Activity "(.+)" chưa được khai báo trong AndroidManifest\.xml$/, (m) => `Activity "${m[1]}" is not declared in AndroidManifest.xml`],
  [/^Có (\d+) file chứa main\(\), chỉ biên dịch (.+)$/, (m) => `${m[1]} files contain main(); only ${m[2]} was compiled`],
  [/^Quá thời gian \((\d+) ms\)$/, (m) => `Time limit exceeded (${m[1]} ms)`],
  [/^Vượt giới hạn RAM \((\d+) MB\)$/, (m) => `Memory limit exceeded (${m[1]} MB)`],
  [/^Chương trình kết thúc với mã (.+)$/, (m) => `Program exited with code ${m[1]}`],
  [/^Zip hỏng: (.*)$/s, (m) => `Corrupted zip: ${m[1]}`],
  [/^Nộp (\d+) lần — đang dùng file mới nhất$/, (m) => `Submitted ${m[1]} times — using the latest file`],
  [/^Nộp (\d+) lần — đang dùng file đã chọn$/, (m) => `Submitted ${m[1]} times — using the selected file`],
  [/^Nộp nhiều lần — đang dùng file đã chọn$/, () => 'Submitted multiple times — using the selected file'],
  [/^MSSV "(.+)" không khớp "Mẫu MSSV" trong Settings \((.*)\) — sửa mẫu rồi quét lại, hoặc gán MSSV tay$/, (m) =>
    `Student ID "${m[1]}" does not match the "Student ID pattern" in Settings (${m[2]}) — fix the pattern and rescan, or assign it manually`],
  [/^Sai định dạng tên file .*— cần gán MSSV$/, () => 'Invalid file name (expected <StudentName>_<StudentID>.zip, e.g. HoDienCong_23546.zip) — assign the student ID manually'],
  // Lỗi test case: "<tên test>: <lỗi>"
  [/^(.+?): (Quá thời gian .*|Vượt giới hạn RAM .*|Output .*|Chương trình kết thúc .*)$/s, (m, tr) => `${m[1]}: ${tr(m[2])}`]
]

/**
 * Dịch chuỗi cố định do app sinh ra và đã lưu (lý do chấm tự động, phân tích tĩnh, ghi chú quét bài...).
 * Các chuỗi này luôn lưu bằng tiếng Việt; chuỗi không nhận ra (vd output trình biên dịch) giữ nguyên.
 */
export function localizeStored(lang: string, s: string): string {
  if (lang !== 'en' || !s) return s
  const exact = EN[s] ?? EN[s.trim()]
  if (exact) return exact
  const tr = (x: string): string => localizeStored(lang, x)
  for (const [re, fn] of EN_PATTERNS) {
    const m = s.match(re)
    if (m) return fn(m, tr)
  }
  return s
}
